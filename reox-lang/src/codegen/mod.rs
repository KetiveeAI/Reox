// REOX Compiler - Code Generator
// Generates C code from typed AST
// Zero external dependencies

use crate::parser::{
    Ast, Decl, Stmt, Expr, Literal, BinOp, UnaryOp, CompoundOp, MatchArm, Pattern,
    FnDecl, StructDecl, ExternDecl, Block, Type, LetStmt,
    ReturnStmt, IfStmt, WhileStmt, ForStmt, GuardStmt, DeferStmt,
    TryCatchStmt, ThrowStmt,
    VariantDecl, ProtocolDecl, ExtensionDecl, LayerDecl, PanelDecl,
    ConstDecl, TypealiasDecl,
};
use crate::lexer::Span;
use std::collections::HashMap;
use std::io::Write;

/// Code generation error, located by a source span when one is known
#[derive(Debug, Clone, PartialEq)]
pub struct CodegenError {
    pub message: String,
    pub span: Span,
}

impl CodegenError {
    pub fn new(message: impl Into<String>, span: Span) -> Self {
        Self { message: message.into(), span }
    }

    pub fn display(&self) -> String {
        format!("codegen error[{}:{}]: {}", self.span.line, self.span.column, self.message)
    }
}

impl std::fmt::Display for CodegenError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(&self.display())
    }
}

impl std::error::Error for CodegenError {}

/// Deepest expression nesting the C backend will emit before reporting an
/// error instead of recursing further.
pub const MAX_EXPR_DEPTH: usize = 1024;

/// Code generator state
pub struct CodeGen {
    output: String,
    indent: usize,
    defer_stack: Vec<Block>,
    closure_counter: usize,
    closure_defs: String,
    expr_depth: usize,
    /// Counter for the temporaries a match expression introduces.
    match_counter: usize,
    /// Payload field names of every variant case, by (variant, case), in
    /// declaration order. Patterns are positional; the C union is not.
    variant_fields: HashMap<(String, String), Vec<String>>,
    /// Functions the program declares itself (fn or extern). The built-in
    /// widget and color rewrites never apply to these.
    declared_fns: std::collections::HashSet<String>,
}

impl CodeGen {
    pub fn new() -> Self {
        Self {
            output: String::new(),
            indent: 0,
            defer_stack: Vec::new(),
            closure_counter: 0,
            closure_defs: String::new(),
            expr_depth: 0,
            match_counter: 0,
            variant_fields: HashMap::new(),
            declared_fns: std::collections::HashSet::new(),
        }
    }

    fn emit(&mut self, s: &str) {
        self.output.push_str(s);
    }

    fn emit_line(&mut self, s: &str) {
        self.emit_indent();
        self.output.push_str(s);
        self.output.push('\n');
    }

    fn emit_indent(&mut self) {
        for _ in 0..self.indent {
            self.output.push_str("    ");
        }
    }

    fn indent(&mut self) {
        self.indent += 1;
    }

    fn dedent(&mut self) {
        if self.indent > 0 {
            self.indent -= 1;
        }
    }

    /// Generate C code from AST
    pub fn generate(&mut self, ast: &Ast) -> Result<String, CodegenError> {
        // Emit header
        self.emit_line("// Generated by REOX Compiler");
        self.emit_line("// Do not edit manually");
        self.emit_line("");
        self.emit_line("#include <stdio.h>");
        self.emit_line("#include <stdlib.h>");
        self.emit_line("#include <stdint.h>");
        self.emit_line("#include <stdbool.h>");
        self.emit_line("#include <string.h>");
        self.emit_line("#include <setjmp.h>");
        self.emit_line("#include \"reox_runtime.h\"");
        self.emit_line("#include \"reox_nxrender_bridge.h\"");  // NXRender integration
        self.emit_line("");

        // Generic declarations only exist as instances; the checker produces them.
        for decl in &ast.declarations {
            let generic = match decl {
                Decl::Function(f) if !f.type_params.is_empty() => Some((&f.name, f.span)),
                Decl::Struct(s) if !s.type_params.is_empty() => Some((&s.name, s.span)),
                Decl::Variant(v) if !v.type_params.is_empty() => Some((&v.name, v.span)),
                Decl::Extension(e) if !e.type_params.is_empty() => Some((&e.target, e.span)),
                _ => None,
            };
            if let Some((name, span)) = generic {
                return Err(CodegenError::new(
                    format!("generic declaration '{}' must be instantiated by the type checker before code generation", name),
                    span,
                ));
            }
        }

        for decl in &ast.declarations {
            match decl {
                Decl::Function(f) => { self.declared_fns.insert(f.name.clone()); }
                Decl::Extern(e) => { self.declared_fns.insert(e.name.clone()); }
                _ => {}
            }
        }

        // Payload layout of every variant, needed to destructure patterns.
        for decl in &ast.declarations {
            if let Decl::Variant(v) = decl {
                for case in &v.cases {
                    let names = case.fields.iter().map(|f| f.name.clone()).collect();
                    self.variant_fields.insert((v.name.clone(), case.name.clone()), names);
                }
            }
        }

        // Forward declarations for structs and variants
        for decl in &ast.declarations {
            match decl {
                Decl::Struct(s) => self.emit_line(&format!("typedef struct {} {};", s.name, s.name)),
                Decl::Variant(v) => self.emit_line(&format!("typedef struct {0} {0};", v.name)),
                Decl::Layer(l) => self.emit_line(&format!("typedef struct {0} {0};", l.name)),
                Decl::Panel(p) => self.emit_line(&format!("typedef struct {0} {0};", p.name)),
                _ => {}
            }
        }
        self.emit_line("");

        // Generate typealias
        for decl in &ast.declarations {
            if let Decl::Typealias(t) = decl {
                self.gen_typealias(t);
            }
        }

        // Generate const
        for decl in &ast.declarations {
            if let Decl::Const(c) = decl {
                self.gen_const(c)?;
            }
        }

        // Generate global variables (top-level let / let mut)
        for decl in &ast.declarations {
            if let Decl::GlobalVar(g) = decl {
                self.gen_global_var(g)?;
            }
        }

        // Generate variant and struct definitions, each after the types it
        // holds by value (generic instances may be declared after their users).
        for decl in self.ordered_type_decls(ast)? {
            match decl {
                Decl::Variant(v) => {
                    self.gen_variant(v);
                    self.emit_line("");
                }
                Decl::Struct(s) => {
                    self.gen_struct(s);
                    self.emit_line("");
                }
                _ => {}
            }
        }

        // Generate protocol (vtable)
        for decl in &ast.declarations {
            if let Decl::Protocol(p) = decl {
                self.gen_protocol(p);
                self.emit_line("");
            }
        }

        // Generate layer and panel structs
        for decl in &ast.declarations {
            match decl {
                Decl::Layer(l) => {
                    self.gen_layer_struct(l);
                    self.emit_line("");
                }
                Decl::Panel(p) => {
                    self.gen_panel_struct(p);
                    self.emit_line("");
                }
                _ => {}
            }
        }

        // Generate extern declarations
        for decl in &ast.declarations {
            if let Decl::Extern(e) = decl {
                self.gen_extern(e);
            }
        }
        if ast.declarations.iter().any(|d| matches!(d, Decl::Extern(_))) {
            self.emit_line("");
        }

        // Generate function prototypes (including methods)
        for decl in &ast.declarations {
            match decl {
                Decl::Function(f) => self.gen_fn_prototype(f),
                Decl::Struct(s) => {
                    for method in &s.methods {
                        self.gen_method_prototype(&s.name, method);
                    }
                }
                Decl::Extension(ext) => {
                    for method in &ext.methods {
                        self.gen_method_prototype(&ext.target, method);
                    }
                }
                Decl::Layer(l) => {
                    for method in &l.methods {
                        self.gen_method_prototype(&l.name, method);
                    }
                }
                Decl::Panel(p) => {
                    for method in &p.methods {
                        self.gen_method_prototype(&p.name, method);
                    }
                }
                _ => {}
            }
        }
        self.emit_line("");

        // Emit closure static functions (generated during expression codegen)
        if !self.closure_defs.is_empty() {
            self.emit(&self.closure_defs.clone());
            self.emit_line("");
        }

        // Generate function implementations
        for decl in &ast.declarations {
            match decl {
                Decl::Function(f) => {
                    self.gen_function(f)?;
                    self.emit_line("");
                }
                Decl::Struct(s) => {
                    for method in &s.methods {
                        self.gen_method(&s.name, method)?;
                        self.emit_line("");
                    }
                }
                Decl::Extension(ext) => {
                    self.gen_extension(ext)?;
                }
                Decl::Layer(l) => {
                    self.gen_layer_methods(l)?;
                }
                Decl::Panel(p) => {
                    self.gen_panel(p)?;
                    self.emit_line("");
                }
                _ => {}
            }
        }

        Ok(self.output.clone())
    }

    /// Struct and variant declarations ordered so that every type appears
    /// after the types its fields hold by value.
    fn ordered_type_decls<'d>(&self, ast: &'d Ast) -> Result<Vec<&'d Decl>, CodegenError> {
        let mut by_name: HashMap<String, &'d Decl> = HashMap::new();
        let mut names: Vec<String> = Vec::new();
        for decl in &ast.declarations {
            let name = match decl {
                Decl::Struct(s) => s.name.clone(),
                Decl::Variant(v) => v.name.clone(),
                _ => continue,
            };
            if by_name.insert(name.clone(), decl).is_none() {
                names.push(name);
            }
        }

        fn by_value_deps(decl: &Decl) -> Vec<String> {
            // Arrays, optionals and functions are pointers in C: no ordering needed.
            fn named(ty: &Type) -> Option<String> {
                match ty {
                    Type::Named(n) => Some(n.clone()),
                    Type::Generic(_, _) => Some(crate::typechecker::ResolvedType::from_parser_type(ty).display_name()),
                    _ => None,
                }
            }
            match decl {
                Decl::Struct(s) => s.fields.iter().filter_map(|f| named(&f.ty)).collect(),
                Decl::Variant(v) => v.cases.iter().flat_map(|c| c.fields.iter().filter_map(|f| named(&f.ty))).collect(),
                _ => Vec::new(),
            }
        }

        fn visit<'d>(
            name: &str,
            by_name: &HashMap<String, &'d Decl>,
            path: &mut Vec<String>,
            done: &mut Vec<String>,
            ordered: &mut Vec<&'d Decl>,
        ) -> Result<(), CodegenError> {
            if done.iter().any(|d| d == name) {
                return Ok(());
            }
            let decl: &'d Decl = match by_name.get(name) {
                Some(d) => d,
                None => return Ok(()), // an extern or runtime type
            };
            if path.iter().any(|p| p == name) {
                let span = match decl {
                    Decl::Struct(s) => s.span,
                    Decl::Variant(v) => v.span,
                    _ => Span::default(),
                };
                path.push(name.to_string());
                return Err(CodegenError::new(
                    format!("type '{}' contains itself by value through {}", name, path.join(" -> ")),
                    span,
                ));
            }
            path.push(name.to_string());
            for dep in by_value_deps(decl) {
                visit(&dep, by_name, path, done, ordered)?;
            }
            path.pop();
            done.push(name.to_string());
            ordered.push(decl);
            Ok(())
        }

        let mut done: Vec<String> = Vec::new();
        let mut ordered: Vec<&'d Decl> = Vec::new();
        for name in &names {
            visit(name, &by_name, &mut Vec::new(), &mut done, &mut ordered)?;
        }
        Ok(ordered)
    }

    fn gen_struct(&mut self, s: &StructDecl) {
        self.emit_line(&format!("struct {} {{", s.name));
        self.indent();
        for field in &s.fields {
            let c_type = self.type_to_c(&field.ty);
            self.emit_line(&format!("{} {};", c_type, field.name));
        }
        self.dedent();
        self.emit_line("};");
    }

    fn gen_extern(&mut self, e: &ExternDecl) {
        let ret_type = e.return_type.as_ref()
            .map(|t| self.type_to_c(t))
            .unwrap_or_else(|| "void".to_string());

        let params: Vec<String> = e.params.iter()
            .map(|p| format!("{} {}", self.type_to_c(&p.ty), p.name))
            .collect();

        let params_str = if params.is_empty() {
            "void".to_string()
        } else {
            params.join(", ")
        };

        self.emit_line(&format!("extern {} {}({});", ret_type, e.name, params_str));
    }

    /// A REOX `main` without a return type is the C entry point `int main`.
    fn is_void_main(f: &FnDecl) -> bool {
        f.name == "main" && f.return_type.is_none()
    }

    fn gen_fn_prototype(&mut self, f: &FnDecl) {
        let ret_type = f.return_type.as_ref()
            .map(|t| self.type_to_c(t))
            .unwrap_or_else(|| if Self::is_void_main(f) { "int".to_string() } else { "void".to_string() });

        let params: Vec<String> = f.params.iter()
            .map(|p| format!("{} {}", self.type_to_c(&p.ty), p.name))
            .collect();

        let params_str = if params.is_empty() {
            "void".to_string()
        } else {
            params.join(", ")
        };

        self.emit_line(&format!("{} {}({});", ret_type, f.name, params_str));
    }

    /// C name of a method: `TypeName_method`.
    fn mangle_method(type_name: &str, method: &str) -> String {
        format!("{}_{}", type_name, method)
    }

    /// `ret TypeName_method(TypeName* self, params)`; static methods take no `self`.
    fn method_signature(&self, type_name: &str, f: &FnDecl) -> String {
        let ret_type = f.return_type.as_ref()
            .map(|t| self.type_to_c(t))
            .unwrap_or_else(|| "void".to_string());

        let mut params: Vec<String> = Vec::new();
        if !f.is_static {
            params.push(format!("{}* self", type_name));
        }
        params.extend(f.params.iter().map(|p| format!("{} {}", self.type_to_c(&p.ty), p.name)));

        let params_str = if params.is_empty() {
            "void".to_string()
        } else {
            params.join(", ")
        };

        format!("{} {}({})", ret_type, Self::mangle_method(type_name, &f.name), params_str)
    }

    fn gen_method_prototype(&mut self, type_name: &str, f: &FnDecl) {
        let signature = self.method_signature(type_name, f);
        self.emit_line(&format!("{};", signature));
    }

    fn gen_method(&mut self, type_name: &str, f: &FnDecl) -> Result<(), CodegenError> {
        self.defer_stack.clear();
        let signature = self.method_signature(type_name, f);
        self.emit_line(&format!("{} {{", signature));
        self.indent();
        self.gen_block(&f.body)?;

        if !self.defer_stack.is_empty() {
            self.emit_deferred_cleanup()?;
        }

        self.dedent();
        self.emit_line("}");
        Ok(())
    }

    fn gen_variant(&mut self, v: &VariantDecl) {
        // Emit C enum for tag
        self.emit_line("typedef enum {");
        self.indent();
        for (i, case) in v.cases.iter().enumerate() {
            let suffix = if i < v.cases.len() - 1 { "," } else { "" };
            self.emit_line(&format!("{}{}", Self::variant_tag(&v.name, &case.name), suffix));
        }
        self.dedent();
        self.emit_line(&format!("}} {}_Tag;", v.name));
        self.emit_line("");

        // Emit tagged union struct
        self.emit_line(&format!("struct {} {{", v.name));
        self.indent();
        self.emit_line(&format!("{}_Tag tag;", v.name));

        // If any case has fields, emit a union
        let has_payload = v.cases.iter().any(|c| !c.fields.is_empty());
        if has_payload {
            self.emit_line("union {");
            self.indent();
            for case in &v.cases {
                if !case.fields.is_empty() {
                    self.emit_line("struct {");
                    self.indent();
                    for field in &case.fields {
                        let c_type = self.type_to_c(&field.ty);
                        self.emit_line(&format!("{} {};", c_type, field.name));
                    }
                    self.dedent();
                    self.emit_line(&format!("}} {};", Self::case_member(&case.name)));
                }
            }
            self.dedent();
            self.emit_line("} data;");
        }

        self.dedent();
        self.emit_line("};");

        // Constructors: a function per case with a payload, a constant otherwise.
        for case in &v.cases {
            let ctor = format!("{}_{}", v.name, case.name);
            let tag = Self::variant_tag(&v.name, &case.name);
            if case.fields.is_empty() {
                self.emit_line(&format!("static const {} {} = {{ .tag = {} }};", v.name, ctor, tag));
                continue;
            }
            let params: Vec<String> = case.fields.iter()
                .map(|f| format!("{} {}", self.type_to_c(&f.ty), f.name))
                .collect();
            self.emit_line(&format!("static inline {} {}({}) {{", v.name, ctor, params.join(", ")));
            self.indent();
            self.emit_line(&format!("{} _rx_v;", v.name));
            self.emit_line(&format!("_rx_v.tag = {};", tag));
            for field in &case.fields {
                self.emit_line(&format!("_rx_v.data.{}.{} = {};", Self::case_member(&case.name), field.name, field.name));
            }
            self.emit_line("return _rx_v;");
            self.dedent();
            self.emit_line("}");
        }
    }

    /// C enumerator of a variant case tag.
    fn variant_tag(variant: &str, case: &str) -> String {
        format!("{}_{}", variant.to_uppercase(), case.to_uppercase())
    }

    /// Name of the union member that holds a case's payload.
    fn case_member(case: &str) -> String {
        case.to_lowercase()
    }

    fn gen_protocol(&mut self, p: &ProtocolDecl) {
        // Protocol → vtable struct of function pointers
        self.emit_line(&format!("typedef struct {}_vtable {{", p.name));
        self.indent();
        for method in &p.methods {
            let ret_type = method.return_type.as_ref()
                .map(|t| self.type_to_c(t))
                .unwrap_or_else(|| "void".to_string());

            let mut params: Vec<String> = vec!["void* self".to_string()];
            for param in &method.params {
                params.push(format!("{} {}", self.type_to_c(&param.ty), param.name));
            }

            self.emit_line(&format!("{} (*{})({});", ret_type, method.name, params.join(", ")));
        }
        self.dedent();
        self.emit_line(&format!("}} {}_vtable;", p.name));
    }

    fn gen_extension(&mut self, ext: &ExtensionDecl) -> Result<(), CodegenError> {
        for method in &ext.methods {
            self.gen_method(&ext.target, method)?;
            self.emit_line("");
        }
        Ok(())
    }

    /// A panel has no fields of its own; its struct exists so that panel
    /// methods can take `self` like every other method.
    fn gen_panel_struct(&mut self, p: &PanelDecl) {
        self.emit_line(&format!("struct {} {{", p.name));
        self.indent();
        self.emit_line("rx_app_t* app;");
        self.dedent();
        self.emit_line("};");
    }

    fn gen_layer_struct(&mut self, l: &LayerDecl) {
        self.emit_line(&format!("struct {} {{", l.name));
        self.indent();
        for field in &l.fields {
            let c_type = self.type_to_c(&field.ty);
            self.emit_line(&format!("{} {};", c_type, field.name));
        }
        // Signal callback slots
        for signal in &l.signals {
            self.emit_line(&format!("void (*{})(void*);", signal.name));
        }
        self.dedent();
        self.emit_line("};");
    }

    fn gen_layer_methods(&mut self, l: &LayerDecl) -> Result<(), CodegenError> {
        for method in &l.methods {
            self.gen_method(&l.name, method)?;
            self.emit_line("");
        }

        // Generate gesture handler callbacks
        for gesture in &l.gestures {
            let fn_name = format!("{}_{}", l.name, gesture.kind);
            let param_strs: Vec<String> = gesture.params.iter()
                .map(|p| format!("{} {}", self.type_to_c(&p.ty), p.name))
                .collect();
            let params_c = if param_strs.is_empty() {
                "void* ctx".to_string()
            } else {
                format!("void* ctx, {}", param_strs.join(", "))
            };

            self.emit_line(&format!("static void {}({}) {{", fn_name, params_c));
            self.indent();
            self.gen_block(&gesture.body)?;
            self.dedent();
            self.emit_line("}");
            self.emit_line("");
        }
        Ok(())
    }

    fn gen_panel(&mut self, p: &PanelDecl) -> Result<(), CodegenError> {
        // Generate panel methods
        for method in &p.methods {
            self.gen_method(&p.name, method)?;
            self.emit_line("");
        }

        // Generate panel setup function
        self.emit_line(&format!("void {}_setup(void) {{", p.name));
        self.indent();
        self.emit_line("rx_app_t* app = rx_app_new();");

        // Emit property assignments
        for (key, value) in &p.properties {
            match key.as_str() {
                "title" => {
                    self.emit_indent();
                    self.emit("rx_app_set_title(app, ");
                    self.gen_expr(value)?;
                    self.emit(");\n");
                }
                "size" => {
                    self.emit_indent();
                    self.emit("rx_app_set_size(app, ");
                    self.gen_expr(value)?;
                    self.emit(");\n");
                }
                _ => {
                    self.emit_line(&format!("/* panel property: {} */", key));
                }
            }
        }

        self.emit_line("rx_app_run(app);");
        self.dedent();
        self.emit_line("}");
        Ok(())
    }

    fn gen_const(&mut self, c: &ConstDecl) -> Result<(), CodegenError> {
        let c_type = c.ty.as_ref()
            .map(|t| self.type_to_c(t))
            .unwrap_or_else(|| "const int64_t".to_string());

        self.emit_indent();
        self.emit(&format!("static const {} {} = ", c_type, c.name));
        self.gen_expr(&c.value)?;
        self.emit(";\n");
        Ok(())
    }

    fn gen_global_var(&mut self, g: &LetStmt) -> Result<(), CodegenError> {
        let c_type = g.ty.as_ref()
            .map(|t| self.type_to_c(t))
            .unwrap_or_else(|| "int64_t".to_string());

        // A type that already carries `const` must not get a second one.
        let qualifier = if g.mutable || c_type.starts_with("const ") {
            "static"
        } else {
            "static const"
        };
        self.emit_indent();
        self.emit(&format!("{} {} {}", qualifier, c_type, g.name));

        if let Some(init) = &g.init {
            self.emit(" = ");
            self.gen_expr(init)?;
        }
        self.emit(";\n");
        Ok(())
    }

    fn gen_typealias(&mut self, t: &TypealiasDecl) {
        let target_c = self.type_to_c(&t.target);
        self.emit_line(&format!("typedef {} {};", target_c, t.name));
    }

    fn gen_function(&mut self, f: &FnDecl) -> Result<(), CodegenError> {
        // Clear defer stack for new function
        self.defer_stack.clear();
        
        let ret_type = f.return_type.as_ref()
            .map(|t| self.type_to_c(t))
            .unwrap_or_else(|| if Self::is_void_main(f) { "int".to_string() } else { "void".to_string() });

        let params: Vec<String> = f.params.iter()
            .map(|p| format!("{} {}", self.type_to_c(&p.ty), p.name))
            .collect();

        let params_str = if params.is_empty() {
            "void".to_string()
        } else {
            params.join(", ")
        };

        self.emit_line(&format!("{} {}({}) {{", ret_type, f.name, params_str));
        self.indent();
        self.gen_block(&f.body)?;
        
        // Emit any remaining deferred cleanup at function end (for void functions)
        if !self.defer_stack.is_empty() {
            self.emit_deferred_cleanup()?;
        }
        if Self::is_void_main(f) {
            self.emit_line("return 0;");
        }
        
        self.dedent();
        self.emit_line("}");
        Ok(())
    }

    fn gen_block(&mut self, block: &Block) -> Result<(), CodegenError> {
        for stmt in &block.statements {
            self.gen_statement(stmt)?;
        }
        Ok(())
    }

    fn gen_statement(&mut self, stmt: &Stmt) -> Result<(), CodegenError> {
        match stmt {
            Stmt::Let(l) => self.gen_let(l)?,
            Stmt::Return(r) => self.gen_return(r)?,
            Stmt::If(i) => self.gen_if(i)?,
            Stmt::While(w) => self.gen_while(w)?,
            Stmt::For(f) => self.gen_for(f)?,
            Stmt::Expr(e) => {
                self.emit_indent();
                self.gen_expr(e)?;
                self.emit(";\n");
            }
            Stmt::Block(b) => {
                self.emit_line("{");
                self.indent();
                self.gen_block(b)?;
                self.dedent();
                self.emit_line("}");
            }
            Stmt::Break(_) => self.emit_line("break;"),
            Stmt::Continue(_) => self.emit_line("continue;"),
            // Swift/C++ style statements
            Stmt::Guard(g) => self.gen_guard(g)?,
            Stmt::Defer(d) => self.gen_defer(d),
            Stmt::TryCatch(t) => self.gen_try_catch(t)?,
            Stmt::Throw(t) => self.gen_throw(t)?,
        }
        Ok(())
    }
    
    fn gen_guard(&mut self, g: &GuardStmt) -> Result<(), CodegenError> {
        // guard condition else { ... }
        // Translates to: if (!(condition)) { ... }
        self.emit_indent();
        self.emit("if (!(");
        self.gen_expr(&g.condition)?;
        self.emit(")) {\n");
        self.indent();
        self.gen_block(&g.else_block)?;
        self.dedent();
        self.emit_line("}");
        Ok(())
    }
    
    fn gen_defer(&mut self, d: &DeferStmt) {
        // Push deferred block onto stack - will be emitted before returns
        self.defer_stack.push(d.body.clone());
    }
    
    fn emit_deferred_cleanup(&mut self) -> Result<(), CodegenError> {
        // Emit all deferred blocks in reverse order (LIFO)
        let blocks: Vec<Block> = self.defer_stack.iter().rev().cloned().collect();
        for block in blocks {
            self.emit_line("/* defer cleanup */");
            self.emit_line("{");
            self.indent();
            self.gen_block(&block)?;
            self.dedent();
            self.emit_line("}");
        }
        Ok(())
    }
    
    fn gen_try_catch(&mut self, t: &TryCatchStmt) -> Result<(), CodegenError> {
        self.emit_line("{");
        self.indent();
        self.emit_line("jmp_buf __rx_jmp;");
        self.emit_line("int __rx_err = setjmp(__rx_jmp);");
        self.emit_indent();
        self.emit("if (__rx_err == 0) {\n");
        self.indent();
        self.gen_block(&t.try_block)?;
        self.dedent();
        self.emit_line("} else {");
        self.indent();
        if let Some(var) = &t.catch_var {
            self.emit_line(&format!("int {} = __rx_err;", var));
        }
        self.gen_block(&t.catch_block)?;
        self.dedent();
        self.emit_line("}");
        self.dedent();
        self.emit_line("}");
        Ok(())
    }
    
    fn gen_throw(&mut self, t: &ThrowStmt) -> Result<(), CodegenError> {
        self.emit_indent();
        self.emit("longjmp(__rx_jmp, (int)(");
        self.gen_expr(&t.value)?;
        self.emit("));\n");
        Ok(())
    }

    fn gen_let(&mut self, l: &LetStmt) -> Result<(), CodegenError> {
        let c_type = l.ty.as_ref()
            .map(|t| self.type_to_c(t))
            .unwrap_or_else(|| "auto".to_string()); // C23 auto or infer from init

        self.emit_indent();
        self.emit(&format!("{} {}", c_type, l.name));

        if let Some(init) = &l.init {
            self.emit(" = ");
            self.gen_expr(init)?;
        }

        self.emit(";\n");
        Ok(())
    }

    fn gen_return(&mut self, r: &ReturnStmt) -> Result<(), CodegenError> {
        // Emit deferred cleanup before return (in reverse order)
        if !self.defer_stack.is_empty() {
            self.emit_deferred_cleanup()?;
        }
        
        self.emit_indent();
        if let Some(value) = &r.value {
            self.emit("return ");
            self.gen_expr(value)?;
            self.emit(";\n");
        } else {
            self.emit("return;\n");
        }
        Ok(())
    }

    fn gen_if(&mut self, i: &IfStmt) -> Result<(), CodegenError> {
        self.emit_indent();
        self.emit("if (");
        self.gen_expr(&i.condition)?;
        self.emit(") {\n");
        self.indent();
        self.gen_block(&i.then_block)?;
        self.dedent();

        if let Some(else_block) = &i.else_block {
            // Detect else-if: single If statement in the else block
            if else_block.statements.len() == 1 {
                if let Stmt::If(nested_if) = &else_block.statements[0] {
                    self.emit_indent();
                    self.emit("} else if (");
                    self.gen_expr(&nested_if.condition)?;
                    self.emit(") {\n");
                    self.indent();
                    self.gen_block(&nested_if.then_block)?;
                    self.dedent();
                    if let Some(final_else) = &nested_if.else_block {
                        self.emit_line("} else {");
                        self.indent();
                        self.gen_block(final_else)?;
                        self.dedent();
                    }
                    self.emit_line("}");
                    return Ok(());
                }
            }
            self.emit_line("} else {");
            self.indent();
            self.gen_block(else_block)?;
            self.dedent();
        }

        self.emit_line("}");
        Ok(())
    }

    fn gen_while(&mut self, w: &WhileStmt) -> Result<(), CodegenError> {
        self.emit_indent();
        self.emit("while (");
        self.gen_expr(&w.condition)?;
        self.emit(") {\n");
        self.indent();
        self.gen_block(&w.body)?;
        self.dedent();
        self.emit_line("}");
        Ok(())
    }

    fn gen_for(&mut self, f: &ForStmt) -> Result<(), CodegenError> {
        match &f.iterable {
            Expr::Range(start, end, _) => {
                // Optimized C loop: for (int64_t i = start; i <= end; ++i)
                self.emit_indent();
                self.emit(&format!("for (int64_t {} = ", f.var));
                self.gen_expr(start)?;
                self.emit(&format!("; {} <= ", f.var));
                self.gen_expr(end)?;
                self.emit(&format!("; ++{}) {{\n", f.var));
                self.indent();
                self.gen_block(&f.body)?;
                self.dedent();
                self.emit_line("}");
            }
            _ => {
                // Default array iteration (simplified for C)
                // Assuming iterable is an array pointer or similar convention
                // This would typically rely on a runtime iterator or Array struct in C
                self.emit_indent();
                // Create unique iterator name
                let iter_name = format!("_iter_{}", f.var);
                self.emit(&format!("array_t* {} = ", iter_name));
                self.gen_expr(&f.iterable)?;
                self.emit(";\n");
                
                self.emit_indent();
                self.emit(&format!("for (int64_t _i = 0; _i < {}->length; ++_i) {{\n", iter_name));
                self.indent();
                self.emit_indent();
                // Extract item
                self.emit(&format!("int64_t {} = {}->data[_i];\n", f.var, iter_name));
                self.gen_block(&f.body)?;
                self.dedent();
                self.emit_line("}");
            }
        }
        Ok(())
    }

    fn gen_expr(&mut self, expr: &Expr) -> Result<(), CodegenError> {
        if self.expr_depth >= MAX_EXPR_DEPTH {
            return Err(CodegenError::new(
                format!("expression nested deeper than {} levels", MAX_EXPR_DEPTH),
                expr.span(),
            ));
        }
        self.expr_depth += 1;
        let result = self.gen_expr_inner(expr);
        self.expr_depth -= 1;
        result
    }

    fn gen_expr_inner(&mut self, expr: &Expr) -> Result<(), CodegenError> {
        match expr {
            Expr::Literal(lit) => self.gen_literal(lit),
            Expr::Identifier(name, _) => self.emit(name),
            Expr::Binary(left, op, right, _) => {
                self.emit("(");
                self.gen_expr(left)?;
                self.emit(&format!(" {} ", self.binop_to_c(op)));
                self.gen_expr(right)?;
                self.emit(")");
            }
            Expr::Unary(op, operand, _) => {
                self.emit(self.unaryop_to_c(op));
                self.gen_expr(operand)?;
            }
            Expr::Call(callee, args, _) => {
                // Built-in UI widget and theme color calls, unless the program
                // declares a function of that name itself.
                if let Expr::Identifier(name, _) = callee.as_ref() {
                    if self.declared_fns.contains(name) {
                        self.gen_expr(callee)?;
                        self.emit("(");
                        for (i, arg) in args.iter().enumerate() {
                            if i > 0 {
                                self.emit(", ");
                            }
                            self.gen_expr(arg)?;
                        }
                        self.emit(")");
                        return Ok(());
                    }
                    match name.as_str() {
                        // UI Widget constructors -> emit reox FFI calls
                        "button" => {
                            self.emit("reox_button_create(");
                            for (i, arg) in args.iter().enumerate() {
                                if i > 0 { self.emit(", "); }
                                self.gen_expr(arg)?;
                            }
                            self.emit(")");
                            return Ok(());
                        }
                        "text" | "label" => {
                            self.emit("reox_label_create(");
                            for (i, arg) in args.iter().enumerate() {
                                if i > 0 { self.emit(", "); }
                                self.gen_expr(arg)?;
                            }
                            self.emit(")");
                            return Ok(());
                        }
                        "input" | "textfield" => {
                            self.emit("reox_textfield_create(");
                            for (i, arg) in args.iter().enumerate() {
                                if i > 0 { self.emit(", "); }
                                self.gen_expr(arg)?;
                            }
                            self.emit(")");
                            return Ok(());
                        }
                        "slider" => {
                            self.emit("reox_slider_create(");
                            for (i, arg) in args.iter().enumerate() {
                                if i > 0 { self.emit(", "); }
                                self.gen_expr(arg)?;
                            }
                            self.emit(")");
                            return Ok(());
                        }
                        "checkbox" => {
                            self.emit("reox_checkbox_create(");
                            for (i, arg) in args.iter().enumerate() {
                                if i > 0 { self.emit(", "); }
                                self.gen_expr(arg)?;
                            }
                            self.emit(")");
                            return Ok(());
                        }
                        "vstack" => {
                            self.emit("reox_vstack(");
                            if !args.is_empty() {
                                self.gen_expr(&args[0])?;
                            } else {
                                self.emit("0");
                            }
                            self.emit(")");
                            return Ok(());
                        }
                        "hstack" => {
                            self.emit("reox_hstack(");
                            if !args.is_empty() {
                                self.gen_expr(&args[0])?;
                            } else {
                                self.emit("0");
                            }
                            self.emit(")");
                            return Ok(());
                        }
                        "window" => {
                            self.emit("reox_window_create(");
                            for (i, arg) in args.iter().enumerate() {
                                if i > 0 { self.emit(", "); }
                                self.gen_expr(arg)?;
                            }
                            self.emit(")");
                            return Ok(());
                        }
                        // Theme colors -> emit directly
                        "color_primary" => { self.emit("(rx_color){0, 122, 255, 255}"); return Ok(()); }
                        "color_secondary" => { self.emit("(rx_color){88, 86, 214, 255}"); return Ok(()); }
                        "color_success" => { self.emit("(rx_color){52, 199, 89, 255}"); return Ok(()); }
                        "color_warning" => { self.emit("(rx_color){255, 149, 0, 255}"); return Ok(()); }
                        "color_danger" => { self.emit("(rx_color){255, 59, 48, 255}"); return Ok(()); }
                        "color_background" => { self.emit("(rx_color){28, 28, 30, 255}"); return Ok(()); }
                        "color_surface" => { self.emit("(rx_color){44, 44, 46, 255}"); return Ok(()); }
                        "color_text" => { self.emit("(rx_color){255, 255, 255, 255}"); return Ok(()); }
                        // Standard function - emit as-is
                        _ => {}
                    }
                }
                // Default: emit as regular function call
                self.gen_expr(callee)?;
                self.emit("(");
                for (i, arg) in args.iter().enumerate() {
                    if i > 0 {
                        self.emit(", ");
                    }
                    self.gen_expr(arg)?;
                }
                self.emit(")");
            }
            Expr::Member(obj, field, _) => {
                self.gen_expr(obj)?;
                // `self` is a pointer inside methods; every other receiver is a value.
                let accessor = if matches!(obj.as_ref(), Expr::SelfRef(_)) { "->" } else { "." };
                self.emit(&format!("{}{}", accessor, field));
            }
            Expr::SelfRef(_) => self.emit("self"),
            Expr::MethodCall(receiver, type_name, method, args, _) => {
                self.gen_method_call(receiver, type_name, method, args)?;
            }
            Expr::Index(arr, idx, _) => {
                self.gen_expr(arr)?;
                self.emit("[");
                self.gen_expr(idx)?;
                self.emit("]");
            }
            Expr::Assign(target, value, _) => {
                self.gen_expr(target)?;
                self.emit(" = ");
                self.gen_expr(value)?;
            }
            Expr::StructLit(name, fields, _) => {
                self.emit(&format!("({}){{", name));
                for (i, (field_name, value)) in fields.iter().enumerate() {
                    if i > 0 {
                        self.emit(", ");
                    }
                    self.emit(&format!(".{} = ", field_name));
                    self.gen_expr(value)?;
                }
                self.emit("}");
            }
            Expr::ArrayLit(elements, _) => {
                self.emit("{");
                for (i, elem) in elements.iter().enumerate() {
                    if i > 0 {
                        self.emit(", ");
                    }
                    self.gen_expr(elem)?;
                }
                self.emit("}");
            }
            Expr::Match(scrutinee, arms, span) => self.gen_match(scrutinee, arms, None, *span)?,
            Expr::Typed(inner, ty, span) => match inner.as_ref() {
                Expr::Match(scrutinee, arms, _) => self.gen_match(scrutinee, arms, Some(ty), *span)?,
                other => self.gen_expr(other)?,
            },
            Expr::Block(block, _) => {
                // A block used as a value: GNU statement expression.
                self.emit("({\n");
                self.indent();
                self.gen_block(block)?;
                self.dedent();
                self.emit_indent();
                self.emit("})");
            }
            // Swift/C++ style expressions
            Expr::CompoundAssign(target, op, value, _) => {
                self.gen_expr(target)?;
                self.emit(&format!(" {} ", self.compound_op_to_c(op)));
                self.gen_expr(value)?;
            }
            Expr::PreIncrement(operand, _) => {
                self.emit("++");
                self.gen_expr(operand)?;
            }
            Expr::PreDecrement(operand, _) => {
                self.emit("--");
                self.gen_expr(operand)?;
            }
            Expr::PostIncrement(operand, _) => {
                self.gen_expr(operand)?;
                self.emit("++");
            }
            Expr::PostDecrement(operand, _) => {
                self.gen_expr(operand)?;
                self.emit("--");
            }
            Expr::NullCoalesce(left, right, _) => {
                // C doesn't have ?? - use ternary conditional
                self.emit("((");
                self.gen_expr(left)?;
                self.emit(") ? (");
                self.gen_expr(left)?;
                self.emit(") : (");
                self.gen_expr(right)?;
                self.emit("))");
            }
            Expr::OptionalChain(obj, field, _) => {
                // C doesn't have ?. - emit regular member access
                self.gen_expr(obj)?;
                self.emit(&format!(".{}", field));
            }
            Expr::TrailingClosure(callee, body, _) => {
                // Emit callee call, then the closure body as a block
                self.gen_expr(callee)?;
                self.emit("; /* trailing closure: */\n");
                self.emit_line("{");
                self.indent();
                self.gen_block(body)?;
                self.dedent();
                self.emit_line("}");
            }
            Expr::Nil(_) => {
                self.emit("NULL");
            }
            Expr::Await(operand, _) => {
                // Emit await as rx_await() runtime call
                self.emit("rx_await(");
                self.gen_expr(operand)?;
                self.emit(")");
            }
            Expr::Range(start, end, _) => {
                // Runtime call to create array from range
                self.emit("rx_range(");
                self.gen_expr(start)?;
                self.emit(", ");
                self.gen_expr(end)?;
                self.emit(")");
            }
            Expr::Action(params, return_type, body, _) => {
                // Generate a static C function for this closure
                let closure_id = self.closure_counter;
                self.closure_counter += 1;
                let fn_name = format!("__rx_closure_{}", closure_id);

                let ret_c = return_type.as_ref()
                    .map(|t| self.type_to_c(t))
                    .unwrap_or_else(|| "void".to_string());

                let param_strs: Vec<String> = params.iter()
                    .map(|p| format!("{} {}", self.type_to_c(&p.ty), p.name))
                    .collect();
                let params_c = if param_strs.is_empty() {
                    "void".to_string()
                } else {
                    param_strs.join(", ")
                };

                // Generate the closure body into the deferred closure definitions buffer
                let mut body_gen = CodeGen::new();
                body_gen.indent = 1;
                body_gen.gen_block(body)?;

                self.closure_defs.push_str(&format!(
                    "static {} {}({}) {{\n{}}}\n\n",
                    ret_c, fn_name, params_c, body_gen.output
                ));

                // Emit the function pointer at the call site
                self.emit(&fn_name);
            }
        }
        Ok(())
    }
    /// Emit a match expression. `result_ty` is the type the checker inferred
    /// for the arms (`None` for an unchecked AST, where only literal patterns
    /// are supported). Flat variant matches become a `switch` on the tag;
    /// nested or literal patterns become an if-else chain.
    fn gen_match(&mut self, scrutinee: &Expr, arms: &[MatchArm], result_ty: Option<&Type>, span: Span) -> Result<(), CodegenError> {
        let id = self.match_counter;
        self.match_counter += 1;
        let m = format!("_rx_m{}", id);
        let r = format!("_rx_r{}", id);

        let (scrutinee, scrutinee_ty) = match scrutinee {
            Expr::Typed(inner, ty, _) => (inner.as_ref(), Some(ty)),
            other => (other, None),
        };
        let uses_variants = arms.iter().any(|a| matches!(a.pattern, Pattern::Variant(_)));
        if uses_variants && (scrutinee_ty.is_none() || result_ty.is_none()) {
            return Err(CodegenError::new(
                "match on a variant needs type information; run the type checker before code generation",
                span,
            ));
        }
        let scrutinee_c = scrutinee_ty.map(|t| self.type_to_c(t)).unwrap_or_else(|| "__auto_type".to_string());
        let is_string = matches!(scrutinee_ty, Some(Type::String));
        // Void (or unknown) result: the match is a statement, nothing is produced.
        let value_mode = match result_ty {
            Some(Type::Void) => false,
            Some(_) => true,
            None => true,
        };
        let result_var = if value_mode { Some(r.as_str()) } else { None };

        self.emit("({\n");
        self.indent();
        self.emit_indent();
        self.emit(&format!("{} {} = ", scrutinee_c, m));
        self.gen_expr(scrutinee)?;
        self.emit(";\n");
        if value_mode {
            match result_ty {
                Some(ty) => {
                    let c = self.type_to_c(ty);
                    self.emit_line(&format!("{} {};", c, r));
                }
                None => self.emit_line(&format!("__typeof__({}) {} = 0;", m, r)),
            }
        }

        let flat = arms.iter().all(|a| Self::is_flat_pattern(&a.pattern));
        let mut seen_cases: Vec<&str> = Vec::new();
        let unique_cases = arms.iter().all(|a| match &a.pattern {
            Pattern::Variant(vp) => {
                if seen_cases.contains(&vp.case.as_str()) { false } else { seen_cases.push(&vp.case); true }
            }
            _ => true,
        });

        if uses_variants && flat && unique_cases {
            self.emit_line(&format!("switch ({}.tag) {{", m));
            let mut has_default = false;
            for arm in arms {
                match &arm.pattern {
                    Pattern::Variant(vp) => {
                        let type_name = vp.type_name.clone().unwrap_or_default();
                        self.emit_line(&format!("case {}: {{", Self::variant_tag(&type_name, &vp.case)));
                        self.indent();
                        let (_, binds) = self.pattern_test(&arm.pattern, &m, is_string)?;
                        for b in binds { self.emit_line(&b); }
                        self.gen_arm_body(&arm.body, result_var)?;
                        self.emit_line("break;");
                        self.dedent();
                        self.emit_line("}");
                    }
                    other => {
                        if has_default { break; }
                        has_default = true;
                        self.emit_line("default: {");
                        self.indent();
                        let (_, binds) = self.pattern_test(other, &m, is_string)?;
                        for b in binds { self.emit_line(&b); }
                        self.gen_arm_body(&arm.body, result_var)?;
                        self.emit_line("break;");
                        self.dedent();
                        self.emit_line("}");
                    }
                }
            }
            if !has_default {
                self.emit_line("default: break;");
            }
            self.emit_line("}");
        } else {
            for (i, arm) in arms.iter().enumerate() {
                let (conds, binds) = self.pattern_test(&arm.pattern, &m, is_string)?;
                let cond = if conds.is_empty() { "1".to_string() } else { conds.join(" && ") };
                self.emit_indent();
                if i == 0 {
                    self.emit(&format!("if ({}) {{\n", cond));
                } else {
                    self.emit(&format!("}} else if ({}) {{\n", cond));
                }
                self.indent();
                for b in binds { self.emit_line(&b); }
                self.gen_arm_body(&arm.body, result_var)?;
                self.dedent();
            }
            if !arms.is_empty() {
                self.emit_line("}");
            }
        }

        if value_mode {
            self.emit_line(&format!("{};", r));
        }
        self.dedent();
        self.emit_indent();
        self.emit("})");
        Ok(())
    }

    /// A pattern a `switch` can dispatch on: a variant case whose payload is
    /// only bound or ignored, a wildcard, or a binding.
    fn is_flat_pattern(p: &Pattern) -> bool {
        match p {
            Pattern::Wildcard | Pattern::Identifier(_) => true,
            Pattern::Variant(vp) => vp.args.iter().all(|a| a.is_irrefutable()),
            Pattern::Literal(_) => false,
        }
    }

    /// Conditions that must hold for `access` to match `pattern`, and the
    /// binding declarations to emit once it does.
    fn pattern_test(&mut self, pattern: &Pattern, access: &str, is_string: bool) -> Result<(Vec<String>, Vec<String>), CodegenError> {
        let mut conds = Vec::new();
        let mut binds = Vec::new();
        match pattern {
            Pattern::Wildcard => {}
            Pattern::Identifier(name) => binds.push(format!("__auto_type {} = {};", name, access)),
            Pattern::Literal(lit) => {
                let mut lit_gen = CodeGen::new();
                lit_gen.gen_literal(lit);
                if is_string || matches!(lit, Literal::String(..)) {
                    conds.push(format!("(rx_strcmp({}, {}) == 0)", access, lit_gen.output));
                } else {
                    conds.push(format!("({} == {})", access, lit_gen.output));
                }
            }
            Pattern::Variant(vp) => {
                let type_name = vp.type_name.clone().ok_or_else(|| CodegenError::new(
                    format!("pattern '{}(..)' was not resolved to a variant; run the type checker before code generation", vp.case),
                    vp.span,
                ))?;
                conds.push(format!("({}.tag == {})", access, Self::variant_tag(&type_name, &vp.case)));
                let fields = self.variant_fields.get(&(type_name.clone(), vp.case.clone())).cloned()
                    .ok_or_else(|| CodegenError::new(
                        format!("variant '{}' has no case '{}'", type_name, vp.case),
                        vp.span,
                    ))?;
                for (i, arg) in vp.args.iter().enumerate() {
                    let field = fields.get(i).ok_or_else(|| CodegenError::new(
                        format!("case '{}' of '{}' has {} field(s), pattern has {}", vp.case, type_name, fields.len(), vp.args.len()),
                        vp.span,
                    ))?;
                    let sub_access = format!("{}.data.{}.{}", access, Self::case_member(&vp.case), field);
                    let (c, b) = self.pattern_test(arg, &sub_access, false)?;
                    conds.extend(c);
                    binds.extend(b);
                }
            }
        }
        Ok((conds, binds))
    }

    /// Emit a match arm body, storing its value in `result_var` when the match
    /// produces one. Block bodies run their statements first.
    fn gen_arm_body(&mut self, body: &Expr, result_var: Option<&str>) -> Result<(), CodegenError> {
        let (stmts, value): (&[Stmt], Option<&Expr>) = match body {
            Expr::Block(block, _) => match block.statements.split_last() {
                Some((Stmt::Expr(last), rest)) => (rest, Some(last)),
                _ => (&block.statements, None),
            },
            other => (&[], Some(other)),
        };
        for stmt in stmts {
            self.gen_statement(stmt)?;
        }
        if let Some(value) = value {
            self.emit_indent();
            if let Some(var) = result_var {
                self.emit(&format!("{} = ", var));
            }
            self.gen_expr(value)?;
            self.emit(";\n");
        }
        Ok(())
    }

    /// `TypeName_method(&receiver, args)`. `self` is already a pointer; a
    /// temporary receiver is materialised first so its address can be taken.
    fn gen_method_call(&mut self, receiver: &Expr, type_name: &str, method: &str, args: &[Expr]) -> Result<(), CodegenError> {
        let callee = Self::mangle_method(type_name, method);
        let is_temporary = !Self::is_place(receiver);
        if is_temporary {
            self.emit(&format!("({{ {} _rx_recv = ", type_name));
            self.gen_expr(receiver)?;
            self.emit(&format!("; {}(&_rx_recv", callee));
        } else {
            self.emit(&format!("{}(", callee));
            if matches!(receiver, Expr::SelfRef(_)) {
                self.emit("self");
            } else {
                self.emit("&(");
                self.gen_expr(receiver)?;
                self.emit(")");
            }
        }
        for arg in args {
            self.emit(", ");
            self.gen_expr(arg)?;
        }
        self.emit(")");
        if is_temporary {
            self.emit("; })");
        }
        Ok(())
    }

    /// Whether `expr` denotes a C lvalue whose address can be taken.
    fn is_place(expr: &Expr) -> bool {
        match expr {
            Expr::Identifier(_, _) | Expr::SelfRef(_) => true,
            Expr::Member(obj, _, _) | Expr::Index(obj, _, _) => Self::is_place(obj),
            _ => false,
        }
    }

    fn compound_op_to_c(&self, op: &CompoundOp) -> &'static str {
        match op {
            CompoundOp::AddEq => "+=",
            CompoundOp::SubEq => "-=",
            CompoundOp::MulEq => "*=",
            CompoundOp::DivEq => "/=",
            CompoundOp::ModEq => "%=",
        }
    }

    fn gen_literal(&mut self, lit: &Literal) {
        match lit {
            Literal::Int(n, _) => self.emit(&format!("{}", n)),
            Literal::Float(n, _) => self.emit(&format!("{:.15}", n)),
            Literal::String(s, _) => self.emit(&format!("\"{}\"", self.escape_string(s))),
            Literal::Bool(b, _) => self.emit(if *b { "true" } else { "false" }),
        }
    }

    fn escape_string(&self, s: &str) -> String {
        let mut result = String::new();
        for ch in s.chars() {
            match ch {
                '\n' => result.push_str("\\n"),
                '\t' => result.push_str("\\t"),
                '\r' => result.push_str("\\r"),
                '\\' => result.push_str("\\\\"),
                '"' => result.push_str("\\\""),
                '\0' => result.push_str("\\0"),
                _ => result.push(ch),
            }
        }
        result
    }

    fn type_to_c(&self, ty: &Type) -> String {
        match ty {
            Type::Int => "int64_t".to_string(),
            Type::Float => "double".to_string(),
            Type::String => "const char*".to_string(),
            Type::Bool => "bool".to_string(),
            Type::Void => "void".to_string(),
            Type::I8 => "int8_t".to_string(),
            Type::U8 => "uint8_t".to_string(),
            Type::I16 => "int16_t".to_string(),
            Type::U16 => "uint16_t".to_string(),
            Type::I32 => "int32_t".to_string(),
            Type::U32 => "uint32_t".to_string(),
            Type::I64 => "int64_t".to_string(),
            Type::U64 => "uint64_t".to_string(),
            Type::USize => "size_t".to_string(),
            Type::Named(name) => name.clone(),
            Type::Generic(_, _) => {
                // Instances are named by the checker (`Box__int`); the fallback
                // mangling here covers ASTs that bypassed it.
                let resolved = crate::typechecker::ResolvedType::from_parser_type(ty);
                resolved.display_name()
            }
            Type::Array(inner) => format!("{}*", self.type_to_c(inner)),
            Type::Optional(inner) => format!("{}*", self.type_to_c(inner)),
            Type::Function(params, ret) => {
                let ret_c = self.type_to_c(ret);
                let params_c: Vec<String> = params.iter().map(|p| self.type_to_c(p)).collect();
                format!("{}(*)({})", ret_c, if params_c.is_empty() { "void".to_string() } else { params_c.join(", ") })
            }
            Type::Tuple(elems) => {
                format!("rx_tuple{}", elems.len())
            }
        }
    }

    fn binop_to_c(&self, op: &BinOp) -> &'static str {
        match op {
            BinOp::Add => "+",
            BinOp::Sub => "-",
            BinOp::Mul => "*",
            BinOp::Div => "/",
            BinOp::Mod => "%",
            BinOp::Eq => "==",
            BinOp::Ne => "!=",
            BinOp::Lt => "<",
            BinOp::Gt => ">",
            BinOp::Le => "<=",
            BinOp::Ge => ">=",
            BinOp::And => "&&",
            BinOp::Or => "||",
            BinOp::BitwiseAnd => "&",
            BinOp::BitwiseOr => "|",
            BinOp::BitwiseXor => "^",
            BinOp::ShiftLeft => "<<",
            BinOp::ShiftRight => ">>",
        }
    }

    fn unaryop_to_c(&self, op: &UnaryOp) -> &'static str {
        match op {
            UnaryOp::Neg => "-",
            UnaryOp::Not => "!",
            UnaryOp::BitwiseNot => "~",
        }
    }
}

impl Default for CodeGen {
    fn default() -> Self {
        Self::new()
    }
}

/// Stack reserved for code generation; see `generate_string`.
const CODEGEN_STACK_BYTES: usize = 64 * 1024 * 1024;

/// Generate C code from AST as a string. Code generation recurses over the
/// expression tree, so it runs on a thread with room for `MAX_EXPR_DEPTH` levels.
pub fn generate_string(ast: &Ast) -> Result<String, CodegenError> {
    std::thread::scope(|scope| {
        let worker = std::thread::Builder::new()
            .name("reox-codegen".to_string())
            .stack_size(CODEGEN_STACK_BYTES)
            .spawn_scoped(scope, || CodeGen::new().generate(ast));
        match worker {
            Ok(handle) => handle.join().unwrap_or_else(|_| {
                Err(CodegenError::new("code generator thread terminated unexpectedly", Span::default()))
            }),
            Err(_) => CodeGen::new().generate(ast),
        }
    })
}

/// Generate C code from AST and write to file. I/O failures are reported
/// as codegen errors naming the output path.
pub fn generate(ast: &Ast, output_path: &str) -> Result<(), CodegenError> {
    let c_code = generate_string(ast)?;

    let io_err = |what: &str, e: std::io::Error| {
        CodegenError::new(format!("failed to {} '{}': {}", what, output_path, e), Span::default())
    };
    let mut file = std::fs::File::create(output_path).map_err(|e| io_err("create", e))?;
    file.write_all(c_code.as_bytes()).map_err(|e| io_err("write", e))?;

    Ok(())
}

